class AdarnaLoadingScreen extends StatefulWidget {
  const AdarnaLoadingScreen({super.key});

  @override
  State<AdarnaLoadingScreen> createState() => _AdarnaLoadingScreenState();
}

class _AdarnaLoadingScreenState extends State<AdarnaLoadingScreen>
    with SingleTickerProviderStateMixin {
  late AnimationController _ctrl;

  late Animation<double> _stringDrawPhase;
  late Animation<double> _fillOpacityPhase;
  late Animation<double> _hoverPhase;
  late Animation<double> _wingFlapPhase;

  @override
  void initState() {
    super.initState();
    _ctrl = AnimationController(
      vsync: this,
      duration: const Duration(seconds: 4),
    )..repeat();

    _stringDrawPhase = Tween<double>(begin: 0.0, end: 1.0).animate(
      CurvedAnimation(
        parent: _ctrl,
        curve: const Interval(0.0, 0.3, curve: Curves.easeInOut),
      ),
    );

    _fillOpacityPhase = Tween<double>(begin: 0.0, end: 1.0).animate(
      CurvedAnimation(
        parent: _ctrl,
        curve: const Interval(0.3, 0.4, curve: Curves.easeIn),
      ),
    );

    _hoverPhase = Tween<double>(begin: 0.0, end: 1.0).animate(
      CurvedAnimation(
        parent: _ctrl,
        curve: const Interval(0.4, 0.9, curve: Curves.easeInOutSine),
      ),
    );

    _wingFlapPhase = Tween<double>(begin: 0.0, end: 1.0).animate(
      CurvedAnimation(
        parent: _ctrl,
        curve: const Interval(0.4, 0.9, curve: Curves.easeInOutSine),
      ),
    );
  }

  @override
  void dispose() {
    _ctrl.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return AnimatedBuilder(
      animation: _ctrl,
      builder: (context, child) {
        final hoverOffset = math.sin(_hoverPhase.value * 3 * math.pi) * 15.0;
        final flapTilt = math.cos(_wingFlapPhase.value * 3 * math.pi) * 0.08;

        final currentOpacity = _ctrl.value > 0.9
            ? (1.0 - ((_ctrl.value - 0.9) * 10))
            : _fillOpacityPhase.value;

        return Center(
          child: Transform(
            alignment: Alignment.center,
            transform: Matrix4.translationValues(
              0.0,
              _ctrl.value > 0.4 ? hoverOffset : 0.0,
              0.0,
            )..rotateZ(_ctrl.value > 0.4 ? flapTilt : 0.0),
            child: SizedBox(
              width: 180,
              height: 180,
              child: Stack(
                alignment: Alignment.center,
                children: [
                  // Phase 1: String Line Drawing
                  CustomPaint(
                    size: const Size(180, 180),
                    painter: StringPathPainter(
                      progress: _stringDrawPhase.value,
                    ),
                  ),
                  // Phase 2 & 3: Solid Color Fill & Flight
                  Opacity(
                    opacity: currentOpacity.clamp(0.0, 1.0),
                    child: CustomPaint(
                      size: const Size(180, 180),
                      painter: SolidLogoPainter(),
                    ),
                  ),
                ],
              ),
            ),
          ),
        );
      },
    );
  }
}

