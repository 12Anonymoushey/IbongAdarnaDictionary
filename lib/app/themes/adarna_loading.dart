Path _centerPath(Path path, Size size, {Rect? bounds}) {
  final pathBounds = bounds ?? path.getBounds();
  if (pathBounds.isEmpty) return path;

  final scale = math.min(
    size.width / pathBounds.width,
    size.height / pathBounds.height,
  );
  final matrix = Matrix4.diagonal3Values(scale, scale, 1).storage;
  final centeredOffset = Offset(
    (size.width - pathBounds.width * scale) / 2,
    (size.height - pathBounds.height * scale) / 2,
  );
  return path
      .shift(Offset(-pathBounds.left, -pathBounds.top))
      .transform(matrix)
      .shift(centeredOffset);
}
